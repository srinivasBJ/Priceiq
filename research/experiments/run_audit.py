from __future__ import annotations
import argparse
from pathlib import Path
from research.src.data_loader import audit_csv

DEFAULTS = ("/Users/trylub/Downloads/amazon_all_electronics_data.csv", "/Users/trylub/Downloads/amazon_india_products_cleaned.csv", "/Users/trylub/Downloads/priceiq_public_history_starter.csv")
def main() -> None:
    p = argparse.ArgumentParser(); p.add_argument("--data", nargs="*", default=DEFAULTS); p.add_argument("--output", default="research/DATASET_AUDIT.md"); args = p.parse_args()
    reports = [audit_csv(path) for path in args.data]
    lines = ["# Dataset audit", "", "Generated by `python -m research.experiments.run_audit`. Classification is conservative: a date column alone is not history.", ""]
    for r in reports:
        semantics = (
            "Repeated timestamped price observations are present but sparse; they are not evidence of continuous/daily tracking."
            if r["classification"] == "SPARSE_PUBLIC_PRICE_HISTORY" else
            "A point-in-time product catalog snapshot, not transaction data or market-price tracking."
            if r["classification"] == "PRODUCT_CATALOG_SNAPSHOT" else
            "Timestamped transaction-like observations, not automatically market-price tracking."
            if r["classification"] == "TRANSACTION_DATA" else
            "Not usable as a price-history observation source.")
        lines += [f"## `{r['filename']}` — `{r['classification']}`", "", f"- Rows: {r['row_count']}; SHA-256: `{r['sha256']}`", f"- Columns: {', '.join(r['columns'])}",
            f"- Dates: {r['date_columns'] or 'none'}; range: {r['earliest_date'] or 'none'} to {r['latest_date'] or 'none'}; unique dates: {r['unique_dates']}",
            f"- Price fields: {r['price_columns'] or 'none'}; product identifiers: {r['product_identifier_columns'] or 'none'}; category fields: {r['category_columns'] or 'none'}",
            f"- Products: {r['unique_products']}; repeated products: {r['repeated_same_product']}; observations/product: {r['observations_per_product']}",
            f"- Missing values: {r['missing_values']}; duplicate rows: {r['duplicate_rows']}", f"- Marketplace/source fields: {r['marketplace_source_columns'] or 'none'}; provenance: {r['provenance']}",
            f"- Observation semantics: {semantics}", f"- Synthetic/generated-field flags: {r['apparent_synthetic_or_generated_fields'] or 'none observed'}", f"- Primary PriceIQ suitability: {r['suitable_for_primary']}. Reason: {r['classification_reason']}", ""]
    Path(args.output).write_text("\n".join(lines) + "\n")
    print(f"Wrote {args.output}")
if __name__ == "__main__": main()
